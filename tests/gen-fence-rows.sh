#!/usr/bin/env bash
# Generator of hooks/fence.rows.ts, the fence's table of shell commands that
# hooks/fence.test.ts asserts shellHits on, from tests/fence-rows.txt: prints
# the file's text on standard output.
#
# A record of the table is a line "# hits: <hits>" (the hits in order,
# separated by ", ", or "none"), a line "# bash: agrees", "# bash: differs:
# <reason> (<detail>)" or "# bash: norun: <why>" (the reason one of not
# observed, a role, a prefix, not earned, wrapped and not read), the
# command's own lines, and a line "# end". Outside a record only empty lines
# and lines that start with "##" stand. A command holds printable ASCII and
# tabs. A hit is one of the kinds the shell's simple commands have, or "a
# here-document left open by a substitution", the scan's refusal to read a
# command, which stands alone and always differs from what bash ran.
#
# Usage: bash tests/gen-fence-rows.sh [--records] [ROWS] > hooks/fence.rows.ts
#   Default ROWS: fence-rows.txt beside this script. With --records it prints
#   instead, for each record, its hits, its bash line's value and its
#   command, each ended by a NUL (tests/check-fence-rows.sh reads them).
#   Exits 1, printing nothing on standard output, on a table not of this
#   form.
set -uo pipefail
export LC_ALL=C

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
mode=ts
if [ "${1:-}" = --records ]; then
  mode=records
  shift
fi
rows=${1:-$here/fence-rows.txt}
nl=$'\n' tab=$'\t'
kinds='a push|a push other than a plain one|a pull request|a merge request|switching noask'
kinds+='|a here-document left open by a substitution'
reasons='not observed|a role|a prefix|not earned|wrapped|not read'

die() {
  printf 'gen-fence-rows: %s\n' "$1" >&2
  exit 1
}
# literal TEXT: TEXT, which holds printable ASCII, tabs and line ends only,
# as a template literal.
literal() {
  local text=$1
  text=${text//\\/\\\\}
  text=${text//\`/\\\`}
  text=${text//\$\{/\\\$\{}
  printf '%s' "\`$text\`"
}
# hits_of HITS: the hits of a record's hits line as a list of strings, in
# TypeScript; fails on a name that is no hit of the shell.
hits_of() {
  local rest=$1 out='' hit
  [ "$rest" != none ] || return 0
  while [ -n "$rest" ]; do
    hit=${rest%%, *}
    [[ $hit =~ ^($kinds)$ ]] || return 1
    out+="${out:+, }'$hit'"
    [ "$hit" != "$rest" ] || break
    rest=${rest#*, }
  done
  printf '%s' "$out"
}

[ -r "$rows" ] || die "cannot read $rows"
hits=() markings=() commands=()
state=out n=0 text='' count=0 hit='' marking=''
while IFS= read -r line || [ -n "$line" ]; do
  n=$((n + 1))
  case $state in
    out)
      if [[ $line =~ ^\#\ hits:\ (.+)$ ]]; then
        hit=${BASH_REMATCH[1]} state=bash
      elif [ -n "$line" ] && [[ $line != '##'* ]]; then
        die "line $n stands outside a record: $line"
      fi
      ;;
    bash)
      [[ $line =~ ^\#\ bash:\ (agrees|differs:\ ($reasons)(\ \(.+\))?|norun:\ .+)$ ]] ||
        die "line $n is no bash line: $line"
      marking=${BASH_REMATCH[1]} state=command text='' count=0
      ;;
    command)
      if [ "$line" = '# end' ]; then
        [[ $text =~ ^[[:print:]$tab$nl]*$ ]] || die "the record that ends on line $n holds more than printable ASCII"
        hits+=("$hit") markings+=("$marking") commands+=("$text")
        state=out
      else
        [ "$count" -eq 0 ] || text+=$nl
        text+=$line count=$((count + 1))
      fi
      ;;
  esac
done < "$rows"
[ "$state" = out ] || die 'the last record has no "# end" line'
[ "${#commands[@]}" -gt 0 ] || die "$rows holds no record"

if [ "$mode" = records ]; then
  for i in "${!commands[@]}"; do
    printf '%s\0%s\0%s\0' "${hits[i]}" "${markings[i]}" "${commands[i]}"
  done
  exit 0
fi

out="// Generated by tests/gen-fence-rows.sh from tests/fence-rows.txt; never edit it by hand: run the script again
// (tests/check-fence-rows.sh compares its output with this file).
import type { FenceWhat } from './fence';

// Each command of the fence's table with the hits shellHits gives it under the home /home/u, in order.
export const FENCE_ROWS: ReadonlyArray<{ readonly command: string; readonly hits: ReadonlyArray<FenceWhat> }> = ["
for i in "${!commands[@]}"; do
  list=$(hits_of "${hits[i]}") || die "record $((i + 1)) names a hit the shell has not: ${hits[i]}"
  out+="
    {
        command: $(literal "${commands[i]}"),
        hits: [$list],
    },"
done
out+="
];"
printf '%s\n' "$out"
